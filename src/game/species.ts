export function skinToSpecies(skin: Skin, force3D = false): Species {
  return {
    ...HERO,
    id: "skin-" + skin.id,
    name: skin.name,
    style: skin.style,
    hRatio: skin.hRatio,
    pal: skin.pal,
    stripes: skin.stripes ?? [],
    spots: !!skin.spots,
    spinyCrest: !!skin.spinyCrest,
    lure: !!skin.lure,
    underbite: !!skin.underbite,
    teeth: !!skin.teeth,
    is3D: !!(force3D && skin.supports3D) || !!skin.is3D,
    eye: skin.eye ?? (skin.style === "orca" ? 0.26 : skin.style === "andy" || skin.style === "boris" ? 0.29 : 0.31),
  };
}

